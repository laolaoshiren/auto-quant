/**
 * **策略师必须有"校准入场门槛"的指令**（2026-10-15）
 *
 * ## 真实情况：它经常读这个工具（65%），而提示词里从没要求过
 *
 * 线上实测（`#11`）：
 * ```
 *   get_skipped_outcomes 被用过 45/69 次（65%）· 最近 30 次里 22 次（73%）
 *   而它的 decisionProcess（1299 字）里【一个字都没提】这个工具
 * ```
 * 也就是说它**自己**觉得该读，但那件事全靠自觉 —— 唯一的"必读"清单
 *（`get_experiments` / `get_lessons` / `get_recent_decisions`）里没有它。
 * 一旦预算紧张，先被砍的就是这种"非必读"项。
 *
 * ## ⚠️ 我第一版的诊断是错的（假阴性），错因值得记住
 *
 * 我最初写的是「最近 8 轮一次都没用」——**那是查询截断造成的假阴性**：
 * ```sql
 *   SELECT substr(agents_json, 1, 400) …    ← 字段实际长 2.3–4.9 KB
 * ```
 * 工具调用列表在中后段，于是全被截成"2-3 个工具"。完整读出来是 6-9 个、
 * **每一轮都有校准工具**。对照实验（同一批记录，截断 vs 完整）复现了这一点。
 *
 * 教训（`docs/AGENTS.md` §3.2）：**不要把"我的查询没看到"当成"它没有发生"。**
 *
 * ## 那这条指令还有必要吗：有
 *
 * ```
 *   · 读它 = 自觉，而必读清单里没有它 → 预算紧时先被砍
 *   · 它上次真的读了数据，结论却是「样本太小，不足以支撑门槛调整」
 *     → 读了却因"不知道样本小该怎么用"而没有行动
 * ```
 * 所以补两件事：**把"可读"变成"该读"**，以及**给样本量的正确用法**。
 *
 * 而那个工具自己的描述（`tools.ts`）写得非常明确：
 * > 「**This is the only feedback that can calibrate your entry standards.**
 * >  If symbols you kept rejecting went up a lot, your filter is too strict —
 * >  that is evidence, not opinion.」
 *
 * 也就是说：**能力在、证据链在、而没人告诉它要用** —— 与 `orchestrator.ts:214`
 * 记录过的形态**一模一样**（原文：「这正是本项目反复出现的形态」）。
 *
 * ## 后果是具体的：它 3 天改了 10 次参数，却无法判断哪次是对的
 *
 * 它自己的原话（`agent_experiments #102`）：
 * ```
 *   「skipped_outcomes 样本太小(10个)……不足以支撑门槛调整」
 *   「现在再动任何参数会让 14:20 的修改无法被归因」
 * ```
 * 推理每一步都对，但结果是**永远不校准** —— 它在用"没有数据"论证"不该动"，
 * 而数据就在它手上没读。
 *
 * ## ⚠️ 样本量的指引也必须给
 *
 * 它上次用"只有 10 个样本"否决了校准。若不给指引，它会永远等一个"足够大"的
 * 样本 —— 而那等于永不校准。样本量的正确用法是**决定"结论能下多强"**，
 * 而不是"要不要看"。
 */
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import test from 'node:test';

import { codeOnly } from '../../testUtils/sourceText.js';
import { strategistTask } from './orchestrator.js';

const SRC = readFileSync(new URL('./orchestrator.ts', import.meta.url), 'utf8');
const CODE = codeOnly(SRC);
const TASK = strategistTask(13);

test('★★★ 任务描述必须提到 get_skipped_outcomes', () => {
  assert.match(
    TASK,
    /get_skipped_outcomes/,
    '★ 必须点名这个工具 —— 它此前只是"可读"，而必读清单里没有它（预算紧时先被砍）',
  );
});

test('★★★ 必须说清"为什么"：只凭盈亏调门槛是在凭结果猜原因', () => {
  /*
   * ⚠️ 光说"要读"不够。要给它**判据**：亏了可能是门槛太严、也可能是门槛太松，
   * 而两者的修法正好相反 —— 只有这个工具能区分。项目里的教训是
   * 「列工具清单不如给判据」。
   */
  assert.match(TASK, /凭结果猜原因/, '★ 要说清"为什么必须看这个数据"');
  assert.match(TASK, /门槛太严/, '★ 要给出两种相反的失败模式');
  assert.match(TASK, /门槛太松/, '★ 两者都要写 —— 只写一个会让它往一边调');
});

test('★★★ 必须给样本量指引（否则它会用"样本太小"否决一切校准）', () => {
  assert.match(
    TASK,
    /样本小不是不读的理由/,
    '★ 实测它用"只有 10 个样本"否决了校准 —— 必须纠正这个用法',
  );
  assert.match(
    TASK,
    /方向性/,
    '★ 要告诉它样本小时该怎么用（下方向性结论，而不是不下结论）',
  );
});

test('★★★ 必须保留原有的"核对规则有没有被遵守"（那条在起作用）', () => {
  /*
   * ⚠️ 实测它每轮都读 `recent_decisions`（41/40 次）—— 那条指令是有效的。
   * 不能因为加新指令而挤掉它。
   */
  assert.match(TASK, /也要核对你写的入场标准有没有被遵守/, '★ 这条不能丢');
  assert.match(TASK, /recent_decisions/, '★ 它靠这个工具核对');
});

test('★★★ 必须保留步数预算提示（否则它不知道怎么规划）', () => {
  assert.match(TASK, /13 次工具调用的预算/, '★ 预算要如实告知');
  assert.match(TASK, /没有结论的这一轮等于白花/, '★ 要说明不产出的代价');
});

test('★★ 注释必须记清【真实的】实测数字（不能把我查错的结果写进去）', () => {
  /*
   * ⚠️ 我第一版写的是「历史上用过 44/68 次，而最近 8 轮一次都没用」——
   * **后半句是假阴性**，来自我的 SQL 截断（`substr(agents_json, 1, 400)`
   * 而字段长 2.3–4.9 KB，工具列表在中后段）。
   * 完整读出来是：**45/69 次（65%）· 最近 30 次里 22 次（73%）**。
   *
   * 所以这条测试钉的是"注释里的数字必须与实测一致"，而不只是"有注释"。
   */
  assert.match(SRC, /45\/69 次（65%）/, '★ 要记真实的历史比例');
  assert.match(SRC, /最近 30 次里 22 次（73%）/, '★ 要记真实的近期比例');
  assert.match(
    SRC,
    /不要把"我的查询没看到"当成"它没有发生"/,
    '★ 必须记下这个假阴性的教训 —— 否则下一个人会重犯',
  );
  assert.match(SRC, /截断 vs 完整/, '★ 要说明是怎么复现出来的（对照实验）');
});

test('★★★ 不得把"最近 8 轮零调用"当成【事实】陈述', () => {
  /*
   * ⚠️ 这是最危险的一类残留：一个**写得很具体**的错误数字。
   * 它比没有注释更糟 —— 下一个人会照它推理。
   *
   * ⚠️ 但**引用它是允许的**（我现在就在引用它，用来记录这个假阴性）。
   * 所以判据必须能区分"作为事实陈述"与"作为被推翻的论断引用"：
   * 后者总带着"我最初的诊断是错的 / 假阴性 / 已被推翻"这类标记。
   */
  const lines = SRC.split('\n');
  for (const [i, line] of lines.entries()) {
    if (!/最近 8 轮/.test(line)) continue;
    /* 取这一行与它前后各 2 行，看上下文有没有"推翻"标记。 */
    const ctx = lines.slice(Math.max(0, i - 2), i + 3).join('\n');
    const marked = /假阴性|已被推翻|我(第一版|最初)写的是|错的|对照实验/.test(ctx);
    assert.ok(
      marked,
      `★ L${i + 1} 提到了"最近 8 轮"却没有标明它已被推翻：\n    ${line.trim()}\n` +
        '  那个论断是查询截断（substr 400 字符）造成的假阴性，真值是 65%。',
    );
  }
  /* 真值必须作为事实出现。 */
  assert.match(SRC, /45\/69 次（65%）/, '★ 真值必须在场');
  assert.doesNotMatch(
    SRC,
    /44\/68 次/,
    '★ 这个数字是截断统计出来的，真值是 45/69',
  );
});

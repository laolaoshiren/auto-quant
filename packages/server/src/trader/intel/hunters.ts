/**
 * 给**一个猎手**写任务提示词（2026-10-13）。
 *
 * ⚠️ 四条共同纪律**每个猎手都要有**（它们都是实测踩出来的）：
 * ```
 *   ① 必须带来源链接 —— 没有链接的情报会被 `parseIntel` 丢掉（它要求 http(s)）
 *   ② 必须给发布时刻（`hoursAgo`）—— 时效衰减与 TTL 判据靠它
 *   ③ 查不到就说查不到 —— 不许用常识填充成"新闻"（那是本项目最忌讳的失败）
 *   ④ 输出 JSON（便于 `parseIntelReport` 解析；解析失败会退回原文）
 * ```
 */
export function buildHunterTask(hunter: HunterRole, symbols: readonly string[]): string {
  return (
    `你是量化机构的「${hunter.label}」。请联网调研这几个标的**今天**的情况：${symbols.join('、')}。\n\n` +
    /*
     * ══════════════════════════════════════════════════════════════════════════
     *  ⚠️⚠️ **"数组放最后"才是对的 —— 上一版"先写数组"在结构上无效**（2026-10-17）
     * ══════════════════════════════════════════════════════════════════════════
     *
     * ## 上一版的推理错在哪
     *
     * 它写的是「先输出 JSON 数组，再去搜更多来源」，理由是"让机器读的东西先写完"。
     * 那条理由在**裁决官**身上成立（预算从末尾砍），但在 harness 上**不成立** ——
     * 因为 `claude --print` **只输出最后一条 assistant 消息**。
     *
     * ## 实测证据（2026-10-17，服务器侧，同一台机器）
     *
     * 让模型「第一步写 [{"summary":"FIRST"}]，然后搜 2 次，最后写 [{"summary":"LAST"}]」：
     * ```
     *   --print（默认）              → 只吐 [{"summary":"LAST"}]
     *   会话 JSONL 里                → assistant.text#1 = FIRST、#2 = LAST（两条都在）
     *   --output-format stream-json  → 两条都能拿到
     * ```
     * ⇒ **先写出的数组会被后续消息覆盖，永远到不了 stdout。**
     * 所以"先写数组"不但没救到它，还给了它一个"我已经写过了"的错觉。
     *
     * ## 线上复现（同一台服务器，20 个标的 = 线上候选池规模）
     *
     * ```
     *   旧措辞（数组在前）+ turns=24 → assistant.text 4 条、tool_use 48 次
     *                                  → 最终 Reached max turns (24) → stdout 29 字节（只有错误行）
     *   新措辞（数组最后 + 写完就停）+ turns=24 → 3 次里 2 次拿到 4 条 / 10 条情报
     * ```
     * 线上那 11 条 `unrecognized_model` 日志里，**每一条都是同样的形状**：
     * 撞轮数上限 + 只有错误行。`unrecognized_model` 本身**不是**原因 ——
     * 实测它在**成功**的会话里同样会出现（它是 CLI 的遥测，且任何非 Anthropic
     * 模型名都会触发它，包括能正常工作的 `opencode-zen-free/*`）。
     *
     * ## 三条纪律（缺一条就回到零产出）
     *
     * ① **数组必须是最后一条消息**，且**写完立刻停止**（再调工具就覆盖掉交付）；
     * ② **搜索次数要有硬上限**（3 次）—— 只说"轮数有限"它仍会一直搜；
     * ③ **按主题搜，不要逐标的搜** —— 20 个标的逐个搜必然用光预算，
     *    而同一批消息本来就会同时影响多个标的（`symbols` 是数组）。
     */
    '## ⚠️ 搜索预算：最多 3 次工具调用（硬上限）\n' +
    '第 4 次调用会被系统直接截断。\n' +
    '**关键机制**：系统只接收你**最后一条**消息 —— 截断时，前面写的内容**全部作废**。\n' +
    '所以结论必须写在**最后**，而不是先写。\n\n' +
    /*
     * ⚠️ 这条"按主题搜"是 20 标的场景能不能有产出的分水岭：
     * 逐标的搜 = 每个标的 2–3 次搜索 = 40–60 次，任何轮数上限都不够。
     */
    '## 怎么搜（**按主题，不要按标的逐个搜**）\n' +
    `这 ${symbols.length} 个标的会一起受同一批消息影响。所以搜**主题**（例如"加密市场今日要闻"、\n` +
    '"BTC ETF 资金流"、"监管动态"），**不要**为每个标的单独搜 —— 那一定会用光预算。\n\n' +
    '## 你必须按这个顺序做\n' +
    '1. 最多 3 次 WebSearch/WebFetch；\n' +
    '2. **然后输出最终 JSON 数组，并且立刻停止** ——\n' +
    '   输出之后**绝对不要**再调用任何工具（那会覆盖掉你的交付）。\n\n' +
    `## 你专查什么\n${hunter.focus}\n\n` +
    `## 优先看这些来源（**但别为了看完它们而不写结论**）\n${hunter.sources.map((s) => `- ${s}`).join('\n')}\n\n` +
    '## 纪律（必须遵守）\n' +
    '1. **只写你真实查到的**。查不到就明确说"本次没有查到相关消息" —— ' +
    '**不要用常识或推测填充成"新闻"**（那会让下游把它当成事实）。\n' +
    '2. 每条消息都要给**来源链接**（http/https 完整地址）。\n' +
    '3. **`hoursAgo` 必须是数字**（不是字符串、不写"约"字）。它决定这条消息还算不算数：\n' +
    '   · **超过 48 小时的消息会被系统判为过期并丢弃** —— 所以只报**最近 48 小时内**的；\n' +
    '   · 你查到的多数东西可能是几天前的旧闻，**那些不要报**（报了也不会被采用）；\n' +
    '   · 如果最近 48 小时内确实没有任何消息，就输出空数组 `[]` —— **那是正确答案**。\n' +
    '4. 说明它对价格的方向含义：利多 / 利空 / 中性。\n' +
    '5. 一条消息可以同时对应多个标的（`symbols` 是数组）。\n\n' +
    '## 输出格式（严格 JSON 数组，**这是你最后一条消息**）\n' +
    '```json\n' +
    '[\n' +
    '  {\n' +
    '    "summary": "一句话说清发生了什么",\n' +
    '    "sourceUrl": "https://…（真实链接，不要编）",\n' +
    '    "direction": "bullish | bearish | neutral",\n' +
    '    "symbols": ["BTCUSDT"],\n' +
    '    "hoursAgo": 3\n' +
    '  }\n' +
    ']\n' +
    '```\n' +
    '⚠️ `hoursAgo` 是**数字**（`3` 而不是 `"3"`、不是 `"约3小时"`）——\n' +
    '类型不对那一条会被整条丢弃。\n' +
    '**查不到任何东西时输出空数组 `[]`** —— 那是正确答案，不是失败。\n' +
    '**数组之后不要再写任何东西、不要再调任何工具。**'
  );
}

/** 一个猎手的产出（含"它是否成功"）。 */
export interface HunterReport {
  hunterId: string;
  label: string;
  ok: boolean;
  text: string;
  error?: string;
  latencyMs: number;
}

/**
 * **合并各猎手的产出**（2026-10-13）。
 *
 * ## 三条设计约束
 *
 * ### ① **每个猎手都要出现**，包括失败的
 *
 * ⚠️ 若把失败者静默丢掉，`newscaster` 会以为"社区上没有任何讨论"——
 * 而事实是"**社区猎手没跑成**"。**那是看不见的失败**（本项目反复强调）。
 *
 * ### ② 失败时**不能假装成功**
 *
 * 产出里写的是"（本次未产出：<原因>）"而不是空字符串 ——
 * 空字符串在下游看起来与"查了但没查到"一模一样。
 *
 * ### ③ **保留来源块**
 *
 * 每条情报的原始 `sourceUrl` 必须原样带过去 ——
 * `intel/freshness.ts` 的交叉验证是**按域名去重**的。
 */
export function mergeHunterReports(reports: readonly HunterReport[]): string {
  if (reports.length === 0) return '';
  /*
   * ⚠️ **必须区分三件事，不能只分两类**（2026-10-15）。
   *
   * ```
   *   ① ok:false                     → 「未产出」（它没跑成 —— 我们不知道那边有什么）
   *   ② ok:true + 剥掉错误行后为空    → 「未查到相关消息」（它跑了，那边确实没消息）
   *   ③ ok:true + 有实质内容          → 正常展示
   * ```
   * ① 与 ② 对下游是**完全不同的信息**：
   * ```
   *   "社区上没有讨论"  vs  "社区猎手挂了"   ← 两件完全不同的事
   * ```
   * 合并它们会让下游把"我不知道"当成"那边没事"。
   *
   * ## 而这次修的是"把错误当产出"（一个新的第 ④ 类）
   *
   * 线上 `research_cache` 的标题写着「**4/4 个猎手有产出**」，
   * 而正文每一节都是 `Error: Reached max turns (12)` ——
   * 因为 `harness.ts` 那时把"stdout 上有错误文本"当成了产出（`ok: true` + 非空 text）。
   *
   * 那一层已修（判据改成"剥掉错误行后还剩不剩实质内容"），
   * 而这里**再独立判一次**：万一将来 `ok` 又被设宽，标题仍应如实反映。
   * ⚠️ 那种情况（`ok:true` 但只有错误行）**不是** ② —— 它一个字都没写，
   * 属于"没跑成"，所以走 ①。
   */
  const stripErrorLines = (t: string): string =>
    t
      .split('\n')
      .filter((line) => !/^\s*(Error:\s*)?Reached max turns/i.test(line))
      .join('\n')
      .trim();
  const substantive = (r: HunterReport): string => (r.ok ? stripErrorLines(r.text) : '');
  const okCount = reports.filter((r) => substantive(r).length > 0).length;
  const lines: string[] = [
    `## 消息面调研（${okCount}/${reports.length} 个猎手有产出）`,
    '',
  ];
  for (const r of reports) {
    lines.push(`### ${r.label}（${r.hunterId}）`);
    const body = substantive(r);
    if (body.length > 0) {
      lines.push(r.text.trim());
    } else if (r.ok && r.text.trim().length === 0) {
      /* ② 它跑了，只是那边确实没有消息。 */
      lines.push('（本次未查到相关消息）');
    } else {
      /*
       * ① 没跑成 —— 必须**显式写出失败**，那是"这个来源本轮缺失"的唯一证据。
       */
      lines.push(`（本次**未产出**：${r.error ?? '未知原因'}）`);
    }
    lines.push('');
  }
  return lines.join('\n');
}

/**
 * **给下游的一句话小结** —— 让 `newscaster` 一眼看到"哪几个来源是缺的"。
 *
 * ⚠️ 为什么单独给这一句：`mergeHunterReports` 的正文很长，
 * 而"有几个来源没产出"是**决策时必须知道的前提**
 *（"社区上没有讨论"与"社区猎手挂了"是两件完全不同的事）。
 */
export function summariseHunters(reports: readonly HunterReport[]): string {
  const failed = reports.filter((r) => !r.ok);
  if (failed.length === 0) {
    return `${reports.length} 个来源全部有产出。`;
  }
  return (
    `${reports.length} 个来源中 **${failed.length} 个未产出**：` +
    `${failed.map((r) => r.label).join('、')} —— ` +
    '**它们的空白不等于"那边没有任何消息"**，请勿据此推断。'
  );
}

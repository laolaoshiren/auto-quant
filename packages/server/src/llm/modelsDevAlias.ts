/**
 * **models.dev 的人工别名表** —— 名字匹配 4 级阶梯里的第 1 级（最高置信）。
 *
 * ## 为什么需要一张*人工*表（而不是全靠算法）
 *
 * 归一化只能吃掉**写法差异**（`deepseek-v4.1-flash` vs `deepseek-v4-1-flash`），
 * 它吃不掉**命名体系统差异**：网关给模型起的名字与上游目录的名字可能毫无字面关系。
 * 那种情况下任何相似度算法都只能靠猜，而**猜错会把参数填到错误的模型上**
 *（后果见下面反例 ①）。
 *
 * 所以留一个人工出口：**确知对应关系时写在这里**，一次性、显式、可 review。
 *
 * ## ⚠️ 收录标准（比"能匹配上"严格得多）
 *
 * 一条别名要进来，必须**同时**满足：
 *
 * 1. **是同一个模型**，不只是"名字像"。区域节点（`-sg` / `@eu`）、量化版本
 *    （`-fp4` / `-TEE`）、上下文压缩版都**不是**同一个模型（见反例 ②）。
 * 2. **参数可以安全共享** —— 至少 `limit.context` 与 `cost` 的口径一致。
 *    实测证明同一模型的免费属性都会因供应商而异，所以这一条要真查过。
 * 3. 有**可复查的依据**（实测记录 / 供应商文档），写进 `why`。
 *
 * **宁缺毋滥**：这张表为空是完全可以接受的；填错一条的代价远大于少填十条。
 *
 * ## 现状：表为空 —— 这不是遗漏，是实测结论（2026-10-14）
 *
 * 对线上网关的 8 个真实模型名实测（见 `modelsDev.test.ts` 的「命中率」用例）：
 *
 * ```
 *   group/auto-deepseek-v4-1-flash    → L2 精确命中（归一化剥 `group/auto-`）
 *   workbuddy-ai/kimi-k3              → L2 精确命中
 *   group/auto-glm-5.3-flash          → L2 精确命中
 *   group/auto-gpt-6-astra            → L2 精确命中
 *   group/auto-ling-3.1-flash-free    → L2 精确命中（归一化剥 `-free`）
 *   group/auto-deepseek-v4-flash      → L2 精确命中
 *   group/auto-minimax-m2.5           → L2 精确命中
 *   group/auto-qfmodel                → **unknown**（见反例 ①）
 * ```
 *
 * **7 个真模型名全部在 L2 就被归一化吃掉了**，没有一个需要人工别名。
 * 所以这里**不写任何条目** —— 为了"让表看起来有内容"而塞进没有依据的映射，
 * 正是这个文件存在的意义所要防的事。
 *
 * ## ⚠️⚠️ 两个【看起来该进来、实际必须留在表外】的反例
 *
 * ### 反例 ①：`qfmodel` —— 它根本不是模型名
 *
 * 实测（2026-10-14，对 `https://models.dev/api.json` 全量 229 provider / 8831 模型）：
 *
 * ```
 *   含 "qfmodel" 的模型条目数 = 0
 *   归一化后 `qfmodel` 在 models.dev 里的最近候选 = `auto-model`，相似度 0.5333
 *   若不剥 `group/auto-` 前缀，最近候选 = `model`，相似度 0.8000
 * ```
 *
 * 两个候选**都是噪声**：`nano-gpt/auto-model` 是"自动挑后端的路由别名"，
 * 它自己的上下文/定价与任何真实模型都无关。而 `qfmodel` 是**网关侧的路由聚合别名**
 *（按名字自动挑供应商，不是一个模型）。
 *
 * 假设代码照单全收（0.80 分就写）：会给这个风控/路由别名填上一个**1,000,000 的
 * 上下文窗口与 0 定价** —— 风控模型拿到一个荒谬的窗口，而"0 定价"会让调度器
 * 以为它免费、把大量活派给它。**填错比不填危险得多**，所以它必须 unknown。
 *
 * 这一点由**代码**（下面的 `MODELS_DEV_UNRESOLVABLE`）而不只是注释强制 ——
 * 注释会被后来的人改，显式清单不会。
 *
 * ### 反例 ②：`deepseek-v4.1-flash-sg` —— 名字像，但不是同一个模型
 *
 * 这条**很容易**被误收进来（相似度 0.9189、版本号 token 都是 `[4,1]`，
 * 连 L4 的模糊门槛都能过）。但同一份实测情报里，网关把两者列成**属性不同**的成员：
 *
 * ```
 *   workbuddy-ai/deepseek-v4.1-flash      free=true     ← 不限量
 *   workbuddy-ai/deepseek-v4.1-flash-sg   free=false    rate=0.03   ← 消耗额度
 * ```
 *
 * `-sg` 是**区域节点**（新加坡），它有独立的额度与（很可能）独立的定价。
 * 用主模型的参数覆盖它，等于把"消耗额度"的成员标注成主模型的值 ——
 * 而 `free` 恰恰是这套系统"合理安排使用"的核心依据。
 *
 * 所以它留在表外：让 L4 用**低置信**的方式去补，且 **只补定价/知识截止**
 *（不补上下文与输出上限，理由见 `modelDiscovery.mergeDiscovered` 里那一段）。
 */

/** 一条人工别名。 */
export interface ModelsDevAliasRule {
  /** 网关上的调用名（写原样即可，匹配时两侧都会归一化）。 */
  from: string;
  /**
   * models.dev 上的目标名 —— 写 `provider/model` 或裸模型名都行。
   *
   * ⚠️ 归一化后必须能在 models.dev 里查到；查不到时匹配逻辑会
   * **忽略这条别名并继续往下一级走**（而不是拿一个空条目去写参数）。
   */
  to: string;
  /** 为什么这条别名成立 —— 写**可复查的依据**，不要写"看起来是同一个"。 */
  why: string;
}

/**
 * 人工别名表。
 *
 * ⚠️ **当前刻意为空** —— 理由见文件头「现状」那一节：
 * 8 个线上真名里 7 个在 L2 精确命中，剩下那个（`qfmodel`）**必须** unknown。
 * 加条目之前请先读「收录标准」与两个反例。
 */
export const MODELS_DEV_ALIASES: readonly ModelsDevAliasRule[] = [];

/**
 * **已知无法归一的网关名** —— 命中的一律返回 `unknown`，不写任何参数。
 *
 * ## 为什么用代码而不是注释强制
 *
 * 本项目的既有教训是「**降低风险的事要靠代码强制，不能靠约定**」。
 * `qfmodel` 的相似度（0.80）离 0.85 的门槛只差 0.05 —— 任何人把阈值
 * 调到 0.8（看起来无害，只是"宽松一点"）都会立刻让它被填上噪声参数。
 * 显式清单把这条边界从"阈值恰好挡住了"变成"**结构上不可能通过**"。
 *
 * ## ⚠️ 这里写的是**已经归一化**的形式
 *
 * 归一化函数在 `modelsDev.ts`（`normalizeGatewayName`）。本模块刻意
 * **不导入它**：别名表是纯数据 + 纯查表，导入主模块会形成
 * `modelsDev ⇄ modelsDevAlias` 的循环依赖，而循环依赖在 ESM 里是否安全
 * 取决于求值顺序 —— 那是一个"今天没事、改一行就炸"的隐患，不值得留。
 *
 * 代价是这里必须手写归一化后的形式。为了不让手写变成坑，
 * `modelsDevAlias.test.ts` 有一条断言：**清单里每一项都必须已经是归一化形式**
 *（即 `normalizeGatewayName(x) === x`）—— 写错会被测试当场抓住。
 */
export const MODELS_DEV_UNRESOLVABLE: readonly string[] = [
  /*
   * 网关的路由聚合别名（按模型名自动挑供应商），**不是模型**。
   * 实测：models.dev 全量 8831 个模型里含 `qfmodel` 的条目数为 **0**。
   * 归一化后会被 `group/auto-qfmodel` / `auto-qfmodel` / `qfmodel` 三种写法同时命中。
   */
  'qfmodel',
];

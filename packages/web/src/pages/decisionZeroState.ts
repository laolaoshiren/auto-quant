/**
 * **"这一轮没有决策" —— 是【判断】还是【故障】？**
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  ⚠️⚠️ 跨模块契约：这里依赖 `deskOutput.ts` 的**报告行字符串**
 * ══════════════════════════════════════════════════════════════════════════
 *
 * 本模块**没有**任何结构化输入 —— 它只能读 `raw_response` 里的自然语言报告行，
 * 而那些报告行是 `packages/server/src/trader/agent/deskOutput.ts`
 * 的 `buildDeskOutput()`（团队审计块那一段，`extracted.status` 的各个分支）写出来的。
 *
 * ```
 *   改 deskOutput.ts 里那些 "⚠️ 裁决…" 的行文
 *     ⇒ 必须同步改本文件的 classifyZeroDecision() 与 decisionZeroState.test.ts
 *     ⇒ 否则界面会把【故障】显示成【观望】（或者反过来），而那不会有任何报错
 * ```
 *
 * ## 这个契约已经因为"靠运气发现"付出过代价
 *
 * ```
 *   2026-10-15  第一版判据漏掉线上真实用词「不可解析」      → 漏报
 *   2026-10-15  第二版把「截断」当词根                      → 误报 64.4%
 *   2026-10-15  第三次：新文案 A 里出现「不是截断」三个字   → 纯词根匹配会把它误判成故障
 * ```
 *
 * 所以：**测试会去 `deskOutput.ts` 里读出真实原文并断言分类**（不是手抄 fixture）。
 * 改后端文案而不改这里 ⇒ `decisionZeroState.test.ts` 变红。这是本模块唯一的守卫，
 * 请**不要**为了让测试变绿去放宽它 —— 那等于把这个契约重新变回"靠运气"。
 *
 * ## 为什么这个判断值得单独抽成模块并单测
 *
 * 界面上原来对"零决策"只有一句文案：
 * ```
 *   没有可执行的决策 — 本周期模型选择观望或持仓。
 * ```
 * 它把**性质完全不同**的情况说成同一件事：
 * ```
 *   ① 模型判断不做（一个【判断】）             —— 正常，无需处理
 *   ② 输出被截断 / 没产出 / 解析失败（【故障】） —— 需要排查
 * ```
 *
 * ## 而情况②真的发生过（线上实测）
 *
 * `#11` 团队模式的裁决官把长文字写进数组每个元素，数组超过输出预算被从末尾砍断：
 * ```
 *   <team> 块里的原文：
 *     ⚠️ 裁决里的 JSON 解析失败（可能被截断）—— 本轮按"不行动"处理。片段：[
 * ```
 * 而界面显示"模型选择观望" —— **于是没有人会去查它**。
 *
 * ⚠️ 与仓库那条纪律一致：**一个把故障说成判断的界面，比一个报错的界面更危险。**
 *
 * ## ⚠️ 判不了的两种情况（不许假装能判）
 *
 * ```
 *   ① `empty`（裁决官真的给出了 `[]`）—— 后端**不写报告行**，文本上与"没产出数组"
 *      没法区分。所以它会落进「观望」。好在它的**结论确实就是"不行动"**，不算说谎。
 *   ② 后端将来新增另一种失败形状 —— 会落到「观望」。这是**刻意的保守方向**
 *      （宁可漏报成观望，也不要误报成故障），并由 test 里的"未知形状"用例钉住。
 * ```
 */

/**
 * 零决策轮的成因分类。**只有 `judgment` 是【判断】**，其余都是【故障】。
 *
 * ⚠️ 取值刻意与 `deskOutput.ts` 的 `extracted.status`（`ok|empty|not-decisions|no-block|bad-json`）
 * **不是**一一对应 —— 这里多出的 `no-block-*` 三种是后端 `no-block` 一个分支内部的细分
 * （`deskOutput.ts` 用 `verdict.ok` 与未闭合围栏区分它们），而 `ok` 不可能是零决策。
 * 名字不同是刻意的：**这里分的是"界面该说什么"**，不是复述后端的状态机。
 */
export type ZeroDecisionKind =
  /** 判断：裁决官以文字给出「不行动」（模型只写了散文）。**不是故障。** */
  | 'no-block-judgment'
  /** 故障：有未闭合的 `[` —— 输出被从数组中间截断。 */
  | 'bad-json'
  /** 故障：裁决官写了 `json` 围栏就停，没有输出数组（模型自己停 / 输出契约问题）。 */
  | 'no-block-truncated'
  /** 故障：裁决官这一轮没有产出（调用失败 / 超时 / 冷却）。 */
  | 'no-block-no-output'
  /** 故障：抓到的是一段"像数组但不是决策数组"的文本（推理里的下标片段）。 */
  | 'not-decisions';

/**
 * 把一段 `raw_response` 分成【判断】与【故障】。
 *
 * ## 判据形状：**组合词根 + 位置**，不是单个词根
 *
 * 为什么不能只看一个词 —— 这是 2026-10-15 那次"误报 64.4%"的直接教训：
 * ```
 *   「截断」这个词在 raw_response 里到处都是（描述别处的截断）：
 *     第  4 轮：「cline/…/step-5-preview → 输出被 token 上限截断，加大 max_tokens 重试」← 与本轮无关
 *     第 85 轮：「bear虽然论证被截断，但方向正确」← 【裁决官在引用它看到的失败】
 *   ⇒ 拿「截断」当判据，非空轮 160 个里误报 103 个。
 * ```
 * 所以每个故障判据都要求**同一句话里的多个词同时在场**（例如「裁决里的 JSON 数组」+
 * 「没有闭合」），而且**只认后端那种报告行的措辞**。
 *
 * ## ⚠️ 新陷阱：判断那一句里**也**有「截断」（2026-10-15 第三次）
 *
 * 后端把"判断"那句改成了：
 * ```
 *   ⚠️ 裁决里没有找到 JSON 数组 —— 裁决官这一轮**以文字给出「不行动」**（模型只写了散文）。
 *   本轮按"不行动"处理，这是它的**判断**（不是截断，无需查预算）。
 * ```
 * 它含「截断」与「预算」两个词 —— **纯词根匹配会把它判成故障**（正是"故障说成观望"的
 * 镜像错误，方向相反但同样是界面上的一句假话）。
 *
 * 处理方式（**我第一版在这里想歪过一次，见下**）：
 * ```
 *   ① 故障判据要求"报告行专属"的组合 —— 「不是截断」不满足任何一条；
 *   ② "这是判断"只能由判断态**自己的正面措辞**来认（「以文字给出「不行动」」）。
 * ```
 *
 * ⚠️ **不要用「不是它的判断」这种否定句去认"这是判断"** —— 我第一版这么写过，是错的：
 * `no-block-no-output`（**故障**）的原文是
 * 「…本轮按"不行动"处理。**这是故障，不是它的判断。**」
 * 它**也**含「不是它的判断」⇒ 那条故障会被认成判断。
 * 否定句在这两种文案里是**对称出现**的，只有正面措辞才可判别。
 *
 * ## 判断顺序（先立后破）
 *
 * 先认「明确的故障」再落「判断」—— 而不是反过来。因为反过来时，任何一句
 * 还没被覆盖的故障文案都会**静默变成"观望"**；而按这个顺序，未覆盖的形状同样落到
 * "观望"（保守方向），但每一句**已覆盖**的故障都有一个正向判据守着它。
 */
export function classifyZeroDecision(rawResponse: string): ZeroDecisionKind {
  const text = rawResponse;

  /*
   * ① 写到自己开的 `json` 围栏就停（没有 `[`）—— 后端原文：
   * 「⚠️ 裁决里的 JSON 数组**没有闭合**（裁决官写到 json 代码块就停了，没有输出数组）——…」
   *
   * ⚠️ **必须排在下面那条之前**：两句都含「JSON 数组**没有闭合**」，
   * 而这一句的括号里写明了原因（写到围栏就停）—— 先认更具体的那一个。
   * 反过来写的话，`no-block-truncated` 永远不可达（值是死的），
   * 而后端那个"模型自己停 vs 数组被截掉"的区分就白做了。
   */
  if (/裁决官写到 ?json ?代码块就停/.test(text)) return 'no-block-truncated';

  /*
   * ② 有未闭合的 `[` —— 最确凿的截断形状。
   * 后端原文：「⚠️ 裁决里的 JSON 数组**没有闭合**（解析失败：输出被截断）——…」
   * 用「没有闭合」而不是「截断」：前者只在这一类句子里出现，
   * 而「截断」在 `raw_response` 里到处都是（历史误报 64.4% 的原因）。
   */
  if (/裁决里的 ?JSON ?数组\*\*没有闭合\*\*/.test(text)) return 'bad-json';

  /*
   * ③ 这一轮没有产出（调用失败 / 超时 / 冷却）—— 后端原文：
   * 「⚠️ 裁决官这一轮**没有产出**（调用失败或超时/冷却）——…**这是故障，不是它的判断。**」
   */
  if (/裁决官这一轮\*\*没有产出\*\*/.test(text)) return 'no-block-no-output';

  /*
   * ④ 抓错数组 —— 后端原文：
   * 「⚠️ 裁决里解析出一段像 JSON 数组的文本，但它**不是决策数组**（元素没有 action 字段）…」
   */
  if (/但它\*\*不是决策数组\*\*/.test(text)) return 'not-decisions';

  /*
   * ⑤ `bad-json` 的另一种：有解析失败但没有未闭合的 `[` —— 后端原文：
   * 「⚠️ 裁决里的 JSON 解析失败 —— 本轮按"不行动"处理。片段：…」
   * ⚠️ 这条与**判断**那句都可能出「JSON」，所以判据必须带「解析失败」这个动作词。
   */
  if (/裁决里的 ?JSON ?解析失败/.test(text)) return 'bad-json';

  /*
   * ══════════════════════════════════════════════════════════════════════════
   *  ⚠️⚠️ 到这里才判「判断」—— 而它的判据必须是**判断态独有的**措辞
   * ══════════════════════════════════════════════════════════════════════════
   *
   * 判断态原文：
   * ```
   *   ⚠️ 裁决里没有找到 JSON 数组 —— 裁决官这一轮**以文字给出「不行动」**（模型只写了散文）。
   *   本轮按"不行动"处理，这是它的**判断**（不是截断，无需查预算）。
   * ```
   *
   * ## 为什么用「以文字给出「不行动」」而不是「不是截断」
   *
   * 我第一版用 `不是它的?判断` 做否定语境排除 —— **那是错的**：
   * `no-block-no-output`（故障态）里写的是
   * 「…本轮按"不行动"处理。**这是故障，不是它的判断。**」
   * 它**也**含「不是它的判断」！于是"否定语境"会把一条真故障认成判断 ——
   * 正是本次要防的那个方向。
   *
   * ⇒ 教训：**否定句不能用来认"这是判断"**，因为故障文案也会说"这不是判断"。
   *   "判断"只能由**它自己的正面措辞**来认。
   *
   * ## 为什么这个顺序（先故障、后判断）而不是反过来
   *
   * 若先判"判断"（例如判"裁决里没有找到 JSON"），那么 ②③ 那两条**也含**类似字样的
   * 故障就会被抢先认成判断。先立（把每个故障的正向判据都过一遍）后破（剩下的才是判断），
   * 任何一条故障文案只要有一条正向判据，就不会被"判断"抢走。
   */
  if (/以文字给出「不行动」/.test(text)) return 'no-block-judgment';

  /*
   * 落到「判断」。
   *
   * ⚠️ 这是**保守方向**：任何还没被上面覆盖的形状（后端将来新增的失败文案、
   * 以及 `empty` 这种后端不写报告行的情况）都会落到这里。
   * 理由与旧版一致：**误报会让操作员去查一个不存在的问题**，
   * 那会消耗掉这个提示的价值；而漏报的方向已经在 test 里用"未知形状"钉住了。
   */
  return 'no-block-judgment';
}

/**
 * 这段原始回复是不是**因为故障**（而不是"模型判断不做事"）才没有决策？
 *
 * ## ⚠️ 它的地位：**兼容入口**，不是"官方布尔 API"（2026-10-15 定）
 *
 * ```
 *   生产代码消费点：0 处
 *   （`DecisionDetailPage` 已改用 `classifyZeroDecision()` —— 它要按成因说不同的话，
 *     只拿到"是故障"这个布尔会把"哪一种故障"丢掉，而那正是这次要修的东西）
 *   仍在使用它的：只有 `decisionZeroState.test.ts` 的 8 条用例
 *   （那些用例记录的是**历史判据的行为**，是一张有价值的回归网，所以留着）
 * ```
 *
 * ## 新代码应该写什么
 *
 * ```
 *   ✅ classifyZeroDecision(raw)   —— 五态分类；需要"该说什么/该查什么"时用它
 *   ⚠️ looksLikeParseFailure(raw)  —— 只在"确实只需要一个布尔"时才用（例如日志/统计）
 * ```
 * 若你发现自己在调用点写 `=== 'no-block-judgment'` 之外的判断逻辑，说明你要的是分类器。
 *
 * ## 为什么不删掉它
 *
 * 它是一个**公开导出**，而公开面的收窄应该谨慎（对应本仓库
 * "不要静默改变行为"的一贯纪律：删导出会让别的分支上的调用点在编译期突然消失）。
 * 所以这里**保留函数 + 补这段说明**，而不是悄悄删掉或者给它套一个 `@deprecated`
 * （后者会引来编辑器/ lint 的噪声，而本仓库没有这个先例）。
 *
 * ⚠️ 判据仍然只有一份：它只是分类器的一层包装 —— **不要在调用点重写正则**。
 */
export function looksLikeParseFailure(rawResponse: string): boolean {
  return classifyZeroDecision(rawResponse) !== 'no-block-judgment';
}

/**
 * **"这一轮没有决策" —— 是【判断】还是【故障】？**
 *
 * ══════════════════════════════════════════════════════════════════════════
 *  ⚠️ 为什么这个判断值得单独抽成模块并单测
 * ══════════════════════════════════════════════════════════════════════════
 *
 * 界面上原来对"零决策"只有一句文案：
 * ```
 *   没有可执行的决策 — 本周期模型选择观望或持仓。
 * ```
 * 它把两种**性质完全不同**的情况说成同一件事：
 * ```
 *   ① 模型判断不做（一个【判断】）             —— 正常，无需处理
 *   ② 输出被截断、解析失败（一个【故障】）      —— 需要排查
 * ```
 *
 * ## 而情况②真的发生过（线上实测）
 *
 * `#11` 团队模式的裁决官把长文字写进数组每个元素，
 * 数组超过输出预算被从末尾砍断：
 * ```
 *   <team> 块里的原文：
 *     ⚠️ 裁决里的 JSON 解析失败（可能被截断）—— 本轮按"不行动"处理。片段：[
 *     attention: 裁决输出不可解析，导致本轮决策链路空转；
 *                需排查裁决角色的输出格式/预算截断问题
 * ```
 * 而界面显示"模型选择观望" —— **于是没有人会去查它**。
 *
 * ⚠️ 与仓库那条纪律一致：**一个把故障说成判断的界面，比一个报错的界面更危险。**
 * （前半句在 `docs/AGENTS.md` 附近有对应记录：一个说错话的错误信息比没有信息更糟。）
 */

/**
 * 这段原始回复是不是**因为解析失败**才没有决策？
 *
 * ## 判据
 *
 * 看 `rawResponse` 里有没有"解析失败 / 被截断"这类字样 ——
 * 它们是 `tradingDesk` **只在真的发生解析失败时**才写进 `<team>` 块的。
 *
 * ## ⚠️ 为什么不用别的判据
 *
 * ```
 *   ✗ 用"回复长度"      —— 实测团队一轮 13,000–16,000 字，而 <decision> 块可能只有
 *                         4 个字符（`[]`）。用长度会得出完全相反的结论。
 *   ✗ 用"decisions 为空" —— 那是【症状】，不是原因（模型真的判断不做时也是空）
 *   ✗ 用"有没有 <team>"  —— 三种模式都有
 * ```
 * 用那三行报错字样是**唯一能区分"判断"与"故障"的信号**。
 *
 * ⚠️ 也可能出现**别的**失败形状（例如模型直接吐了一段散文、
 * 连"解析失败"都没写）。那时这个函数会返回 `false` ——
 * 那是保守的方向：**宁可漏报成"观望"，也不要误报成"故障"**
 *（误报会让操作员去查一个不存在的问题）。
 */
export function looksLikeParseFailure(rawResponse: string): boolean {
  /*
   * ══════════════════════════════════════════════════════════════════════════
   *  ⚠️⚠️ 判据是从**线上 264 条记录里穷举出来的**，不是我猜的（2026-10-15）
   * ══════════════════════════════════════════════════════════════════════════
   *
   * ## 我前两版都错了，错法不同
   *
   * ```
   *   第一版 /解析失败|被截断/                 → 漏（线上真实用词是"不可解析"）
   *   第二版 /解析失败|无法解析|不可解析|被截断|截断/
   *          → 误报率 64.4%（非空轮 160 个里误报 103 个）
   * ```
   * 第二版为什么误报那么多 —— 逐条看过原文：
   * ```
   *   第  4 轮：「cline/…/step-5-preview → 输出被 token 上限截断，加大 max_tokens 重试」
   *             ← 模型降级链的日志，与本轮成败无关
   *   第  5 轮：「多空论证均被截断(做多第三部分缺失)」← 某角色产出被截，但本轮 20 条决策正常
   *   第 85 轮：「bear虽然论证被截断，但方向正确」  ← 【裁决官在引用它看到的失败】
   * ```
   * ⇒ 「截断」这个词在 `raw_response` 里**到处都是**，描述的都是**别的地方**的截断。
   *
   * ## 正确的做法：穷举「只出现在空决策轮」的报告行
   *
   * 把 264 条记录里所有"系统在报告本轮异常"的行抽出来，按
   * 「是否只在空决策轮出现」筛：
   * ```
   *   ✅ 只在空轮出现（27 次）:
   *      ⚠️ 裁决里没有找到 JSON 数组 —— 模型可能只写了散文。本轮按"不行动"处理。
   *   ✅ 只在空轮出现（6 次）:
   *      ⚠️ 裁决里的 JSON 解析失败（可能被截断）—— 本轮按"不行动"处理。片段：[
   *
   *   ❌ 两种轮次都出现（192 次：空 74 / 非空 118）—— 不能当判据:
   *      ⚠️ 本轮未经风控官审阅（风控角色未启用或调用失败）—— 决策按裁决官结论直接放行。
   * ```
   * 最后那条特别值得记：它看起来很像"系统坏了"，但它**在正常轮次里也出现**
   *（风控官本来就不是每轮都启用）—— 拿它当判据会误报 74 次。
   *
   * ## 所以判据只认这两条**特定的**报告行
   *
   * 它们的共同点：都是"裁决环节没能产出数组"这一类 ——
   * 即**决策链路的最后一环失败**，而不是"模型判断不做"。
   *
   * ⚠️ 宁可漏（把真故障说成"观望"）也不要误报 ——
   * 误报会让操作员去查一个不存在的问题，那会消耗掉这个提示的价值。
   */
  return /裁决里没有找到 ?JSON|裁决里的 ?JSON ?解析失败|裁决[^\n]{0,10}不可解析/.test(rawResponse);
}

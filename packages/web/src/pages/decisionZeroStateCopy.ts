/**
 * **"这一轮没有决策"的界面文案** —— 按 `classifyZeroDecision()` 的五态各说各的。
 *
 * ## 为什么要把文案从组件里抽出来
 *
 * 组件里原来只有**两支**：`parseFailure ? "输出解析失败（可能被截断）" : "观望"`。
 * 而分类器（`decisionZeroState.ts`，2026-10-15）已经能分出四种故障：
 * ```
 *   bad-json            数组没闭合（被截断）        → 查输出预算 max_tokens
 *   no-block-truncated  开了 json 围栏却没写完      → 不装"是 token 上限"，只说现象
 *   no-block-no-output  裁决官这一轮没有产出        → 查网关 / 冷却 / 额度（不是预算问题）
 *   not-decisions       抓到的是推理里的下标片段    → 不是模型的错
 * ```
 * 把它们都说成"可能被截断"的后果很具体：**操作员会去查一个不存在的预算问题**，
 * 而真因（网关不可达）没人看。这就是本次迭代的同一个病，只是换了一层：
 * 分类器已经分好了，界面却还在说同一句话 —— **分类没被用上等于没分类**。
 *
 * ## 这个模块的边界（只说事实，不编原因）
 *
 * ```
 *   ① 每一条都只描述**已经看到的东西**（文本形状 / 调用结果），不推断没有证据的原因；
 *   ② `no-block-truncated` 那条**故意不写**"是 token 上限" —— 后端在
 *      `deskOutput.ts` 里明确说了它不装（"写完围栏就停"与"数组被截掉"在文本上相同）。
 *      我也不装。
 *   ③ `empty`（裁决官真的给出 `[]`）**没有单独文案** —— 后端不写报告行、
 *      前端在文本上区分不了它，所以它落在"观望"。那个取舍写在下面那条上。
 * ```
 */

import type { ZeroDecisionKind } from './decisionZeroState';

/**
 * 一条零决策文案的**声明**（没有 React 依赖 —— 所以可单测、也可被别的渲染层复用，
 * 而且一个组件渲染不出来时，能直接断言表本身有没有被人改坏）。
 */
export interface ZeroDecisionCopy {
  /** 一句话结论（加粗、着色）。必须是**事实陈述**，不是猜测。 */
  headline: string;
  /** 支撑说明：这是什么、下一步查什么。 */
  detail: string;
}

/**
 * 五态 → 文案。
 *
 * ⚠️ **写成 `Record<ZeroDecisionKind, …>`（穷尽映射）而不是 `switch` 的 `/` 兜底**：
 * `decisionZeroState.ts` 将来加一种故障时，这里**编译不过** ——
 * 而不是静默落进某一条已有文案（那正是"分类没被用上"的复发方式）。
 */
export const ZERO_DECISION_COPY = {
  /* ── 【故障】数组没闭合：确凿的截断形状 ─────────────────────────────── */
  'bad-json': {
    headline: '本轮**没有决策**，原因是裁决输出**被截断**（JSON 数组没有闭合）。',
    detail:
      '这不是模型判断"不做"。这类失败会**整轮丢掉决策**，需要排查输出预算（`max_tokens`）' +
      '或让模型把每条决策写短。报错原文见下方「原始模型响应」一节。',
  },

  /* ── 【故障】开了 json 围栏却没写完 ─────────────────────────────────── */
  'no-block-truncated': {
    headline: '本轮**没有决策**：裁决官开了 `json` 代码块，但**没有写完数组**。',
    detail:
      '这不是模型判断"不做"。⚠️ 它的文本形状（"有围栏、没有数组"）与"数组被截掉"**无法区分**，' +
      '所以这里不断言是 token 上限 —— 排查时**先看它的输出是不是真的短**，再看预算。' +
      '原文见下方「原始模型响应」一节。',
  },

  /* ── 【故障】裁决官这一轮没有产出（网关/冷却/超时） ──────────────────── */
  'no-block-no-output': {
    headline: '本轮**没有决策**：裁决官这一轮**没有产出**（调用失败或超时/冷却）。',
    detail:
      '**这不是输出预算问题，也不是模型判断"不做"** —— 它压根没被跑出来。' +
      '下一步查模型网关的连通性、额度与冷却状态（`/v1/magpie/quotas`），再看调用日志。',
  },

  /* ── 【故障】抓错了数组（推理里的下标片段） ─────────────────────────── */
  'not-decisions': {
    headline: '本轮**没有决策**：抓到的那段"像数组的文本"**不是决策数组**。',
    detail:
      '它通常是裁决官推理过程里的**下标片段**（元素没有 `action` 字段），' +
      '所以**不能算成它的决策** —— 这一条更像是解析端的责任，不是模型没给结论。' +
      '原文见下方「原始模型响应」一节。',
  },

  /* ── 【判断】观望（含 `empty`，见下） ───────────────────────────────── */
  'no-block-judgment': {
    headline: '没有可执行的决策 — 本周期模型选择观望或持仓。',
    detail:
      '⚠️ 这一句同时覆盖两种语义：**裁决官以文字给出「不行动」**（判断），' +
      '以及**它给出了空数组 `[]`**（`empty`）。后者在后端**不写报告行**，' +
      '所以前端在文本上分不开它们 —— 两者的结论都是"本轮不动"，因此这里合并显示是诚实的；' +
      '但"到底是哪种"这个信息在界面上**看不到**（见 `decisionZeroState.ts` 的边界说明）。',
  },
} satisfies Record<ZeroDecisionKind, ZeroDecisionCopy>;

/**
 * 取一条零决策文案。
 *
 * `kind` 直接来自 `classifyZeroDecision()` —— 中间不做任何字符串判断，
 * 于是"分类"与"文案"之间没有第二份判据（那会是下一个漂移点）。
 */
export function zeroDecisionCopy(kind: ZeroDecisionKind): ZeroDecisionCopy {
  return ZERO_DECISION_COPY[kind];
}

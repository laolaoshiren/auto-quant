/**
 * **显示前把文本里的 markdown 强调符号剥掉**（`**粗体**`）。
 *
 * ## 为什么需要它（2026-10-15 用真实浏览器量到的）
 *
 * 用户要求「功能布局要合理，方便用户使用，**用户体验至上**」。
 * 用 `document.body.innerText` 统计真实页面，发现界面上原样显示着：
 * ```
 *   汇总多空论证，给出**唯一**结论（有权决定"不行动"）        ← firm.ts 的 duty
 *   它**没有被执行**，但也不是"模型没给" —— 原始内容见…        ← parser.ts 的拒单理由
 *   `deepseek` 档位**耗尽**了额度                            ← 模型/服务端的理由
 * ```
 * 那些 `**` 是**写给模型与维护者看的强调标记**，而界面是给人读的纯文本、
 * 不是 markdown 渲染器 —— 用户看到只会当成界面 bug。
 *
 * ## ⚠️ 与 `memberSummary.ts` 的分工（不是重复实现）
 *
 * `summarizeMemberOutput()` 也剥 markdown，但它剥的是**摘要提取**那一步的一部分
 * （`**` + `##` 标题 + 行内代码 + 列表符）—— 它的目标是"从长产出里切出一句人话"。
 *
 * 而这里是**显示层的最后一道**：文本**原样展示**给用户之前，把不属于纯文本的
 * 装饰符号去掉。它刻意**只剥 `**`**：
 * ```
 *   ✗ 剥 `#`   —— 技术文本里的 `#` 有别的含义（URL 片段、编号）
 *   ✗ 剥 `     —— 反引号常用来标出代码/模块名，剥掉会丢掉"这是代码"的暗示
 *   ✗ 剥 `__`  —— 它在标识符里很常见（模块名、字段名），误剥会**静默改掉一个事实**
 * ```
 * 换句话说：**只剥那种"看错了会以为是界面坏了"的符号，其余一律不动。**
 *
 * ⚠️ **不引入 markdown 渲染器**：把可信文本渲染成 HTML 会开出一个注入面，
 * 为这点收益不值得（本仓库不引入新依赖的同一条纪律）。
 */
export function plainText(text: string): string {
  return text.replace(/\*\*/g, '');
}

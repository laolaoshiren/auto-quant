/**
 * 委托行上的**标记**判据 —— 纯函数，放在这里是为了能被单独测。
 *
 * 它从 `components/TraderTables.tsx` 里搬出来：那个文件 import 了 React、
 * lucide-react 与一堆界面组件，`node --test` **import 不动它**（会拉起浏览器
 * 依赖）。而这条判据前后错了两次、用户连着问了两次，它值得有自己的用例。
 *
 * ## ⚠️ 判据**不是**一个"状态词"（2026-10-17 · 台账 ORD-01 / 用户实测 U-3）
 *
 * 用户原话：
 *
 * > 「当前委托里面出现：**已挂单（待对账）**。（待对账）这个是设计之初就明确说过
 * >  **不需要也不能出现**的（应该完全由系统内部处理，而不是显示在网站上）。」
 *
 * 他说得对，而且这不是措辞问题：把**内部处理过程**摆成订单的一个状态，
 * 等于给每一行都可能挂上一个"账实不符"的告警 —— 那是**虚假的对账告警**。
 * 所以：
 * ```
 *   状态列  → 只说委托自己的事实（已挂单 / 已成交 / 已撤销…）
 *   这个标记 → 只进 title（错开的读数怎么回事、下一步谁去确认）
 * ```
 * 判据本身保留：它背后有**真实事故**（本地 36 条"已挂单"而交易所 0 条），
 * 删掉它就是把那次事故的守卫一起删掉。
 */

/**
 * 这张"还挂着"的委托，值不值得**提醒操作员"这份读数可能对不上"**？
 *
 * ## 它在抓什么
 *
 * `orders.status` 是**下单那一刻**交易所给的返回值，之后由服务端的对账
 * （`AutoTrader.settleStaleOrders()`）在确认"交易所已经不挂着了"之后改写。
 * 所以界面上的 `NEW` 只代表"上一次对账之后它还是这个状态"。
 *
 * 判据故意取得很窄，宁可少标也不要错标：只有**整本账都没有持仓**时，
 * 一张仍然写着挂单的委托才值得怀疑（实盘上那 16 行孤儿委托，每一个标的的
 * 本地持仓都是 0）。有持仓时保护单本来就该挂在那里 —— 标上去只会制造假警报，
 * 而**假警报和数据缺失一样会让这个界面失去信任**。
 *
 * ## ⚠️ 入场单不算可疑 —— 它在成交之前，整本账本来就是空的
 *
 * 这正是"没有持仓"这条判据唯一抓错的地方。一张**限价入场单**从挂出到成交之间
 * 必然没有持仓，那是它的**正常状态**，不是"账本可能错了"。
 *
 * 实测（用户连着两次问到这里）：一张 `03:23:14` 挂出的 HYPEUSDT 限价单，
 * 界面上写着「已挂单（待对账）」，他的原话是「这个不是系统应该自动自主
 * 实时处理的吗」。**答案是：它本来就在正常等待，没有任何东西需要处理。**
 *
 * ## ⚠️⚠️ 模拟盘**一律不标**（2026-10-17 新增的输入）
 *
 * 模拟盘（`dryRun`）的订单**从不出现在交易所**（`broker.ts` 的 `simulateStandard`
 * 路径）—— 交易所永远不可能"确认"或"否认"它。拿"本地挂单数 ≠ 交易所读数"
 * 去判模拟盘，等于问一个**不存在的问题**，而答案必然是"对不上"
 * （实测：模拟盘的保护单 100% 命中，与"实盘真的有孤儿委托"长得一模一样）。
 *
 * 所以这一条现在是**必填**输入，而不是可选 —— 漏传时应该编译不过，
 * 而不是静默退回"按实盘判"。
 */
export function needsReconcileFlag(input: {
  /** 调用点手里这份列表是不是"只显示了还挂着的那些"。 */
  onlyOpen: boolean;
  /** 这张单**此刻**是否仍处于非终态（由调用点用 `isOpenOrder` 判好再传进来）。 */
  stillOpen: boolean;
  /** 用途。`entry` = 限价入场单，它在成交前本来就没有持仓。 */
  purpose: string;
  /** 界面手上的持仓条数。 */
  positionCount: number;
  /**
   * 这台机器人在不在模拟盘（`stats.dryRun === true`）。
   * 模拟盘不存在"交易所孤儿委托"这种情况 —— 见上面那段。
   */
  paper: boolean;
}): boolean {
  if (input.paper) return false;
  return (
    input.onlyOpen && input.stillOpen && input.positionCount === 0 && input.purpose !== 'entry'
  );
}

/**
 * 上面那个标记为真时，**给操作员看的那句话**（订单状态列的 `title`）。
 *
 * 它必须回答三件事：① 交易所那边最后一次说它是什么；② 为什么值得注意；
 * ③ 谁去把它弄明白（服务端对账，不需要操作员动手）。
 *
 * 抽成函数是为了能被用例钉住措辞：**这句话里不允许出现「待对账」这个术语**
 * （它只描述现象与下一步），而"允许出现"的地方由 `ORD-01` 的用例守着。
 */
export function reconcileNoteTitle(status: string): string {
  return (
    `交易所在上一次对账时给这张单的状态是 ${status}。本地台账里没有任何持仓 —— ` +
    '它可能在交易所那边已经成交或被撤销，服务端下一次对账会确认并改写本地状态；' +
    '本地台账与交易所读数的差异同时会记进服务端日志与审计面板。'
  );
}


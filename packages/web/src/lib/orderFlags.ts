/**
 * 这张"还挂着"的委托，值不值得打上「**待对账**」？
 *
 * ## 它在抓什么
 *
 * `orders.status` 是**下单那一刻**交易所给的返回值，之后由服务端的对账
 * （`AutoTrader.settleStaleOrders()`）在确认"交易所已经不挂着了"之后改写。
 * 所以界面上的 `NEW` 只代表"上一次对账之后它还是这个状态"。
 *
 * 判据故意取得很窄，宁可少标也不要错标：只有**整本账都没有持仓**时，
 * 一张仍然写着挂单的委托才值得怀疑（实盘上那 16 行孤儿委托，每一个标的的
 * 本地持仓都是 0）。有持仓时保护单本来就该挂在那里 —— 标上去只会制造假警报，
 * 而**假警报和数据缺失一样会让这个界面失去信任**。
 *
 * ## ⚠️ 但入场单不算可疑 —— 它在成交之前，整本账本来就是空的
 *
 * 这正是"没有持仓"这条判据唯一抓错的地方。一张**限价入场单**从挂出到成交之间
 * 必然没有持仓，那是它的**正常状态**，不是"账本可能错了"。把它标成「待对账」，
 * 等于给每一张刚挂出的单都挂上一个"数据可能不对"的警告，而这个警告会一直挂到
 * 它成交或被撤（最长 `pendingEntryTimeoutMinutes`）。
 *
 * 实测（用户连着两次问到这里）：一张 `03:23:14` 挂出的 HYPEUSDT 限价单，
 * 界面上写着「已挂单（待对账）」，他的原话是「这个不是系统应该自动自主
 * 实时处理的吗」。**答案是：它本来就在正常等待，没有任何东西需要处理。**
 *
 * 真正可疑的是**保护单**：有止损/止盈挂着、而整本账没有任何持仓 ——
 * 那才是"委托与持仓对不上"。
 *
 * ## 入场单成交之后由谁纠正
 *
 * `applyExchangeFill()`（成交推送到达即对账）与 `settleStaleOrders()`（对账兜底），
 * 两条路都在服务端。**界面不需要用一个警告去替它们兜底** —— 那只会让操作员
 * 学会忽略这个颜色，而那正是这个标记存在的意义所在。
 */
export function needsReconcileFlag(input: {
  /** 调用点手里这份列表是不是"只显示了还挂着的那些"。 */
  onlyOpen: boolean;
  /** 这张单**此刻**是否仍处于非终态（由调用点用 `isOpenOrder` 判好再传进来）。 */
  stillOpen: boolean;
  /** 用途。`entry` = 限价入场单，它在成交前本来就没有持仓。 */
  purpose: string;
  /** 界面手上的持仓条数。 */
  positionCount: number;
}): boolean {
  return (
    input.onlyOpen && input.stillOpen && input.positionCount === 0 && input.purpose !== 'entry'
  );
}
